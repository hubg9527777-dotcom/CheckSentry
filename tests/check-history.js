// Static integration checks only; Windows PowerShell & native Prefetch tests run separately on Windows.
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.join(__dirname, '..');
const code = fs.readFileSync(path.join(root, 'Start-ComplianceCheck.ps1'),'utf8');
const scanner = fs.readFileSync(path.join(root, 'Get-ExecutionHistory.ps1'),'utf8');
const ui = fs.readFileSync(path.join(root, 'report_template.html'),'utf8');
const proj = fs.readFileSync(path.join(root,'launcher','CheckSentry.Launcher.csproj'),'utf8');
const manifest = fs.readFileSync(path.join(root,'launcher','app.manifest'),'utf8');
assert(code.includes("Kind = 'Execution'"), 'new background job missing');
assert(code.includes("Execution = @($script:InventoryScanResults.Execution)"), 'scan results not merged');
assert(code.includes('Get-ExecutionAuditHtml -Inventory $Inventory'), 'history section absent');
assert(code.includes("$route -eq '/api/execution/reveal'"), 'secure local location action missing');
assert(code.includes('if ([bool]$entry.PathVerified -and $path'), 'unvalidated inferred paths must not be directly revealable');
assert(!/Start-Process\s+[^\r\n]*-FilePath\s+\$target/i.test(code), 'target executable must never be run');
assert(ui.includes('execFilter') && ui.includes('execSearch') && ui.includes('exec-reveal'), 'report controls missing');
assert(scanner.includes('RtlDecompressBufferEx') && scanner.includes('PrefetchReader'), 'Prefetch native read missing');
assert(scanner.includes("Id = 4688") && scanner.includes("Kind = '脚本'"), 'batch execution lead not implemented');
assert(scanner.includes('Get-CheckSentryRunningProcessEvidence'), 'current process fallback absent');
assert(scanner.includes('Get-CheckSentryBamEvidence'), 'BAM execution artifact fallback absent');
assert(scanner.includes('Get-CheckSentryUserAssistEvidence'), 'non-admin UserAssist fallback absent');
assert(scanner.includes('非确定的进程执行证明'), 'GUI-interaction-only evidence must be identified');
assert(code.includes('仅 GUI 交互线索'), 'rule matching must not overstate UserAssist as execution');
assert(code.includes('exec-coverage-alert'), 'prefetch failures must be visible without expanding details');
assert(ui.includes('white-space: normal !important') && ui.includes('table-layout: fixed'), 'historical table must wrap long paths');
assert(code.includes('exec-action-row'), 'path buttons must be separated from long evidence text');
assert(code.includes('疑似免安装（执行已记录，位置待验证）'), 'Prefetch-only portable execution must remain prominent even when path is unvalidated');
assert(code.includes('历史执行已记录，位置待确认'), 'Prefetch-only execution must not disappear because its path is missing');
assert(scanner.includes('if ($pfName.Length -ge 29)'), 'truncated Prefetch executable names must be handled conservatively');
assert(!/Get-CheckSentryPecmdEvidence|PECmd\\.exe/i.test(scanner), 'PECmd must not be launched without explicit user approval');
assert(!proj.includes('Tools\\PECmd'), 'PECmd must not be embedded in product EXE');
assert(proj.includes('Get-ExecutionHistory.ps1') && proj.includes('1.2.0'), 'launcher payload/version incomplete');
assert(manifest.includes('asInvoker'), 'main program must preserve active user profile for extensions');
assert(!/https?:\/\//i.test(scanner), 'execution scanner must not contact network endpoints');
console.log('Execution integration structure, UX hooks, read-only sources and version checks passed (static).');
